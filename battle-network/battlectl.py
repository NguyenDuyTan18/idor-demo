"""Prepare and run the instructor-side two-sandbox battle deployment."""
import argparse
import json
import re
import shlex
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent
TERRAFORM = ROOT / 'terraform'
UUID = re.compile(r'^[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}$')


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError('Battle config must be a JSON object')
    pool_id = config.get('pool_id')
    if isinstance(pool_id, bool) or not isinstance(pool_id, int) or pool_id <= 0:
        raise ValueError('pool_id must be a positive integer')
    cloud = config.get('cloud_name')
    if cloud is not None and (not isinstance(cloud, str) or not cloud.strip()):
        raise ValueError('cloud_name must be a non-empty string or null')
    teams = config.get('teams')
    if not isinstance(teams, dict) or set(teams) != {'A', 'B'}:
        raise ValueError('teams must contain exactly A and B')

    sandbox_ids = []
    server_ids = []
    for name in ('A', 'B'):
        team = teams[name]
        if not isinstance(team, dict):
            raise ValueError(f'Team {name} must be an object')
        for key in ('sandbox_uuid', 'kali_server_id', 'web_server_id'):
            value = team.get(key)
            if not isinstance(value, str) or not UUID.fullmatch(value):
                raise ValueError(f'Team {name} {key} must be a UUID')
        sandbox_ids.append(team['sandbox_uuid'].lower())
        server_ids.extend([team['kali_server_id'].lower(), team['web_server_id'].lower()])
        ssh_config = Path(str(team.get('management_ssh_config', ''))).expanduser()
        if not ssh_config.is_absolute() or not ssh_config.is_file():
            raise ValueError(f'Team {name} management SSH config must be an existing absolute file')

    if len(set(sandbox_ids)) != 2 or len(set(server_ids)) != 4:
        raise ValueError('Use two distinct sandbox UUIDs and four distinct Nova VM UUIDs')
    return config


def _inventory(config):
    lines = [
        '# Generated by battlectl.py; instructor-only and gitignored.',
        'all:',
        '  vars:',
        '    ansible_python_interpreter: /usr/bin/python3',
        '  children:',
        '    battle_hosts:',
        '      hosts:',
    ]
    for team_name in ('A', 'B'):
        path = Path(config['teams'][team_name]['management_ssh_config']).resolve().as_posix()
        ssh_args = f'-F {shlex.quote(path)} -o ControlMaster=no -o ControlPath=none'
        for role in ('kali', 'web'):
            lines.extend([
                f'        team-{team_name.lower()}-{role}:',
                f'          ansible_host: {role}',
                '          ansible_user: debian',
                f'          ansible_ssh_common_args: {json.dumps(ssh_args)}',
            ])
    return '\n'.join(lines) + '\n'


def prepare(config, runtime):
    validate_config(config)
    runtime = Path(runtime)
    runtime.mkdir(parents=True, exist_ok=True)
    tfvars = {
        'cloud_name': config.get('cloud_name'),
        'pool_id': config['pool_id'],
        'teams': {
            name: {key: team[key] for key in ('sandbox_uuid', 'kali_server_id', 'web_server_id')}
            for name, team in config['teams'].items()
        },
    }
    (runtime / 'terraform.auto.tfvars.json').write_text(
        json.dumps(tfvars, indent=2) + '\n', encoding='utf-8')
    (runtime / 'inventory.yml').write_text(_inventory(config), encoding='utf-8')
    return runtime


def commands_for(action, runtime):
    runtime = Path(runtime).resolve()
    tf = ['terraform', '-chdir=' + str(TERRAFORM)]
    var_file = '-var-file=' + str(runtime / 'terraform.auto.tfvars.json')
    plan_file = str(runtime / 'battle.tfplan')
    inventory = str(runtime / 'inventory.yml')
    playbook = str(ROOT / 'configure-guests.yml')
    init = tf + ['init']
    validate = tf + ['validate']
    plan = tf + ['plan', var_file, '-out=' + plan_file]
    if action == 'plan':
        return [init, validate, plan]
    if action == 'deploy':
        return [init, validate, tf + ['apply', plan_file],
                tf + ['output', '-json'],
                ['ansible-playbook', '-i', inventory, playbook]]
    if action == 'verify':
        return [['ansible-playbook', '-i', inventory, playbook]]
    raise ValueError(f'Unsupported action: {action}')


def require_reviewed_plan(config, runtime):
    runtime = Path(runtime)
    plan = runtime / 'battle.tfplan'
    snapshot = runtime / 'reviewed-config.json'
    if not plan.is_file() or not snapshot.is_file():
        raise ValueError('A reviewed battle plan is required; run the plan action first')
    reviewed = json.loads(snapshot.read_text(encoding='utf-8'))
    if reviewed != config:
        raise ValueError('Battle config changed after plan review; run the plan action again')


def run(action, config_path, runtime):
    config = json.loads(Path(config_path).read_text(encoding='utf-8'))
    runtime = prepare(config, runtime).resolve()
    output_path = ROOT / 'cloud-outputs.json'
    if action == 'deploy':
        require_reviewed_plan(config, runtime)
    if action == 'verify' and not output_path.is_file():
        raise ValueError('cloud-outputs.json is missing; run deploy first')
    for command in commands_for(action, runtime):
        print('+', ' '.join(command), flush=True)
        try:
            result = subprocess.run(command, check=True, text=True,
                                    capture_output=command[-2:] == ['output', '-json'])
        except FileNotFoundError as error:
            raise RuntimeError(f'Required executable not found: {command[0]}') from error
        if command[-2:] == ['output', '-json']:
            output_path.write_text(result.stdout, encoding='utf-8')
    if action == 'plan':
        (runtime / 'reviewed-config.json').write_text(
            json.dumps(config, sort_keys=True), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description='Connect two allocated IDOR sandboxes')
    parser.add_argument('action', choices=['plan', 'deploy', 'verify'])
    parser.add_argument('--config', default=str(ROOT / 'battle-config.json'))
    parser.add_argument('--runtime', default=str(ROOT / '.runtime'))
    args = parser.parse_args()
    try:
        run(args.action, args.config, args.runtime)
    except (OSError, ValueError, RuntimeError, json.JSONDecodeError,
            subprocess.CalledProcessError) as error:
        print(f'battlectl: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
